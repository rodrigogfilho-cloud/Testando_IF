#MÉDIA DO COLEGA

média = float(input("Digite a sua média escolar:"))
if média >= 7:
    print("Parabéns! Você foi aprovado")
elif média >= 5:
    print("Você terá uma segunda chance, está de recuperação")
else:
    print("Você é um(a) FRACASSADO(A). Está REPROVADO!!!")

